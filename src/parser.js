// ===== G-CODE PARSER =====
export class GcodeParser {
  constructor() {
    this.lines = [];
    this.layers = [];
    this.headerEnd = 0;
    this.fileName = '';
    this.warnings = [];
    this.skippedLines = 0;
  }

  _detectSlicer(lines) {
    const scanLines = Math.min(50, lines.length);
    for (let i = 0; i < scanLines; i++) {
      const line = lines[i];
      if (line.includes('Generated with Cura_SteamEngine')) return 'cura';
      if (line.includes('generated by PrusaSlicer')) return 'prusaslicer';
      if (line.includes('generated by SuperSlicer')) return 'superslicer';
      if (line.includes('generated by OrcaSlicer')) return 'orcaslicer';
      if (line.includes('G-Code generated by Simplify3D')) return 'simplify3d';
      if (line.includes('Sliced by ideaMaker')) return 'ideamaker';
      if (line.includes('BambuStudio') || line.includes('Bambu Studio')) return 'bambu';
    }
    return 'unknown';
  }

  _detectMode(lines) {
    // FDM signals (any => fdm)
    const slicer = this._detectSlicer(lines);
    if (slicer !== 'unknown') return 'fdm';

    const scanLines = Math.min(500, lines.length);
    let hasExtrusionMode = false;
    let hasEParam = false;
    let hasSpindle = false;
    let hasToolChange = false;
    let hasArc = false;

    for (let i = 0; i < scanLines; i++) {
      // Strip line numbers (N<num>) and inline (...) comments, then insert a
      // space between digit-letter pairs so concatenated tokens like "T4M06"
      // or "G00G21G17" split into separate \b-bounded words.
      const line = lines[i]
        .replace(/^\s*N\d+\s*/i, '')
        .replace(/\([^)]*\)/g, '')
        .replace(/(\d)([A-Z])/gi, '$1 $2');
      if (/\bM8[23]\b/.test(line)) hasExtrusionMode = true;
      if (/\bG[01]\b.*\bE-?[\d.]+/i.test(line)) hasEParam = true;
      if (/\bM0?[35]\b/.test(line)) hasSpindle = true;
      if (/\bM0?6\b/.test(line)) hasToolChange = true;
      if (/\bG0?[23]\b/.test(line)) hasArc = true;
    }

    if (hasExtrusionMode || hasEParam) return 'fdm';
    if (hasSpindle || hasToolChange) return 'cnc';
    if (hasArc) return 'cnc'; // arcs without E strongly suggest CNC
    return 'fdm'; // safe default
  }

  async _parseCNC(lines, onProgress) {
    const Z_EPSILON = 0.001;
    this.layers = [];
    this.layerMoves = {};
    this.bounds = { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity, minZ: Infinity, maxZ: -Infinity };
    this.headerEnd = 0;
    this.warnings = [];
    this.skippedLines = 0;
    this.tools = new Set();
    this.spindleRPMs = new Set();
    this.feedRates = new Set();

    let curX = 0, curY = 0, curZ = 0;
    let currentFeedRate = 0;
    let currentSpindleRPM = 0;
    let currentTool = null;
    let spindleOn = false;
    let foundFirstMove = false;
    // Modal motion mode (G0/G1/G2/G3): subsequent lines with X/Y/Z but no G use
    // the last motion code. VCarve/Vectric posts rely on this constantly.
    let modalMotion = 0; // 0=G0 rapid, 1=G1 feed, 2=G2 CW arc, 3=G3 CCW arc

    const zBands = new Map(); // zKey -> layer object
    const getOrCreateBand = (z) => {
      const zKey = Math.round(z / Z_EPSILON);
      let layer = zBands.get(zKey);
      if (!layer) {
        layer = {
          number: this.layers.length,
          startLine: 0, endLine: null,
          zHeight: z,
          sectionTypes: ['FEED'],
          lineCount: 0
        };
        this.layers.push(layer);
        this.layerMoves[layer.number] = [];
        zBands.set(zKey, layer);
      }
      return layer;
    };

    const recordMove = (x1, y1, z1, x2, y2, z2, type, lineIndex) => {
      const bandZ = Math.max(z1, z2);
      const layer = getOrCreateBand(bandZ);
      layer.lineCount++;
      if (!layer.sectionTypes.includes(type)) layer.sectionTypes.push(type);
      this.layerMoves[layer.number].push({
        x1, y1, x2, y2, z1, z2,
        type, extrude: false, lineIndex,
        feedRate: currentFeedRate,
        spindleRPM: currentSpindleRPM,
        tool: currentTool
      });
      this.bounds.minX = Math.min(this.bounds.minX, x1, x2);
      this.bounds.maxX = Math.max(this.bounds.maxX, x1, x2);
      this.bounds.minY = Math.min(this.bounds.minY, y1, y2);
      this.bounds.maxY = Math.max(this.bounds.maxY, y1, y2);
      this.bounds.minZ = Math.min(this.bounds.minZ, z1, z2);
      this.bounds.maxZ = Math.max(this.bounds.maxZ, z1, z2);
    };

    const CHUNK = 50000;
    const total = lines.length;

    for (let start = 0; start < total; start += CHUNK) {
      const end = Math.min(start + CHUNK, total);
      for (let i = start; i < end; i++) {
        // Normalize: strip leading N<num> (Vectric/Mach-style line numbers) and
        // inline (...) comments, then insert a space between digit-letter pairs
        // so concatenated tokens ("T4M06", "G00G21G17", "X0.000Y0.000") become
        // \b-bounded words. matchAll patterns work either way; the spaces just
        // ensure \b anchors fire between codes.
        const raw = lines[i];
        const line = raw
          .replace(/^\s*N\d+\s*/i, '')
          .replace(/\([^)]*\)/g, '')
          .replace(/(\d)([A-Z])/gi, '$1 $2')
          .trim();

        if (!foundFirstMove && line && !line.startsWith(';') && /^[GMT]/.test(line)) {
          this.headerEnd = i;
          foundFirstMove = true;
        }

        // Spindle / tool changes can co-occur with G codes on the same line
        // (e.g. "T4M06"). Detect them regardless of position.
        if (/\bM0?3\b/.test(line)) {
          spindleOn = true;
          const sm = line.match(/\bS([\d.]+)/i);
          if (sm) { currentSpindleRPM = parseFloat(sm[1]); this.spindleRPMs.add(currentSpindleRPM); }
        }
        if (/\bM0?5\b/.test(line)) { spindleOn = false; }
        if (/\bM0?6\b/.test(line) || /\bT\d+\b/.test(line)) {
          const tm = line.match(/\bT(\d+)/i);
          if (tm) { currentTool = parseInt(tm[1]); this.tools.add(currentTool); }
        }

        // Update modal motion if a G0/G1/G2/G3 appears anywhere on the line.
        // Match the LAST such code so "G00G21G17G90..." correctly sets motion
        // from any leading motion code; CAM posts typically put motion first
        // but consecutive G's on one line are valid.
        const motionMatches = [...line.matchAll(/\bG0?([0123])\b/g)];
        let motionExplicit = false;
        if (motionMatches.length > 0) {
          modalMotion = parseInt(motionMatches[0][1]);
          motionExplicit = true;
        }

        // Has any axis/feed/arc params?
        const hasAnyParam = /[XYZIJRF]-?[\d.]/i.test(line);
        if (!hasAnyParam && !motionExplicit) continue;
        // If a motion G code appears but no XYZ params (e.g. "G00G21G17G90..."
        // setup line, or G80 cancel), nothing to draw — skip.
        if (!hasAnyParam) continue;

        if (modalMotion === 0 || modalMotion === 1) {
          try {
            const params = {};
            for (const m of line.matchAll(/([XYZF])(-?[\d.]+)/gi)) params[m[1].toUpperCase()] = parseFloat(m[2]);

            const newX = params.X !== undefined ? params.X : curX;
            const newY = params.Y !== undefined ? params.Y : curY;
            const newZ = params.Z !== undefined ? params.Z : curZ;
            if (params.F !== undefined) { currentFeedRate = params.F; this.feedRates.add(currentFeedRate); }

            const isG0 = modalMotion === 0;
            const dx = newX - curX, dy = newY - curY, dz = newZ - curZ;
            const hasXY = dx !== 0 || dy !== 0;
            const hasZ = dz !== 0;

            let type;
            if (isG0) type = 'RAPID';
            else if (hasZ && dz < 0 && !hasXY) type = 'PLUNGE';
            else if (hasZ && dz > 0 && !hasXY) type = 'LIFT';
            else type = 'FEED';

            if (hasXY || hasZ) {
              recordMove(curX, curY, curZ, newX, newY, newZ, type, i);
            }

            curX = newX; curY = newY; curZ = newZ;
          } catch (err) { this.skippedLines++; }
          continue;
        }

        if (modalMotion === 2 || modalMotion === 3) {
          try {
            const params = {};
            for (const m of line.matchAll(/([XYZFIJR])(-?[\d.]+)/gi)) params[m[1].toUpperCase()] = parseFloat(m[2]);

            const newX = params.X !== undefined ? params.X : curX;
            const newY = params.Y !== undefined ? params.Y : curY;
            const newZ = params.Z !== undefined ? params.Z : curZ;
            if (params.F !== undefined) { currentFeedRate = params.F; this.feedRates.add(currentFeedRate); }
            const isG2 = modalMotion === 2;

            let cx, cy, r;
            if (params.I !== undefined || params.J !== undefined) {
              cx = curX + (params.I || 0);
              cy = curY + (params.J || 0);
              r = Math.hypot(params.I || 0, params.J || 0);
            } else if (params.R !== undefined) {
              const mx = (curX + newX) / 2, my = (curY + newY) / 2;
              const dx = newX - curX, dy = newY - curY;
              const d = Math.hypot(dx, dy);
              r = Math.abs(params.R);
              const h = Math.sqrt(Math.max(0, r * r - (d / 2) * (d / 2)));
              const sign = (isG2 ? -1 : 1) * (params.R > 0 ? 1 : -1);
              cx = mx + sign * (-dy / d) * h;
              cy = my + sign * ( dx / d) * h;
            } else {
              curX = newX; curY = newY; curZ = newZ;
              continue;
            }

            if (r > 0.01) {
              let startAngle = Math.atan2(curY - cy, curX - cx);
              let endAngle = Math.atan2(newY - cy, newX - cx);
              if (isG2) {
                if (endAngle >= startAngle) endAngle -= 2 * Math.PI;
              } else {
                if (endAngle <= startAngle) endAngle += 2 * Math.PI;
              }
              const segments = Math.max(4, Math.ceil(Math.abs(endAngle - startAngle) / (Math.PI / 12)));
              let prevAX = curX, prevAY = curY, prevAZ = curZ;
              for (let s = 1; s <= segments; s++) {
                const t = s / segments;
                const angle = startAngle + (endAngle - startAngle) * t;
                const ax = s === segments ? newX : cx + r * Math.cos(angle);
                const ay = s === segments ? newY : cy + r * Math.sin(angle);
                const az = curZ + (newZ - curZ) * t;
                recordMove(prevAX, prevAY, prevAZ, ax, ay, az, 'ARC', i);
                prevAX = ax; prevAY = ay; prevAZ = az;
              }
            }

            curX = newX; curY = newY; curZ = newZ;
          } catch (err) { this.skippedLines++; }
          continue;
        }
      }

      if (onProgress) onProgress(Math.min(end / total, 1));
      if (end < total) await new Promise(r => setTimeout(r, 0));
    }

    // Sort layers by Z ascending and renumber
    this.layers.sort((a, b) => a.zHeight - b.zHeight);
    const remap = new Map();
    this.layers.forEach((layer, idx) => { remap.set(layer.number, idx); });
    const newLayerMoves = {};
    for (const [oldNum, moves] of Object.entries(this.layerMoves)) {
      const newNum = remap.get(parseInt(oldNum));
      newLayerMoves[newNum] = moves;
    }
    this.layerMoves = newLayerMoves;
    this.layers.forEach((layer, idx) => { layer.number = idx; });

    if (!isFinite(this.bounds.minX)) this.bounds = { minX: 0, maxX: 256, minY: 0, maxY: 256, minZ: 0, maxZ: 0 };
  }

  async parseAsync(text, fileName, onProgress) {
    this.fileName = fileName;
    this.lines = text.split(/\r?\n/);
    this.slicerType = this._detectSlicer(this.lines);
    this.mode = this._detectMode(this.lines);
    this.layers = [];
    this.layerMoves = {};
    this.bounds = { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity };
    this.headerEnd = 0;
    this.warnings = [];
    this.skippedLines = 0;

    let currentLayer = null;
    let foundFirstLayer = false;
    // State machine for tracking head position
    let curX = 0, curY = 0, curZ = 0, curE = 0;
    let relativeE = false; // M83 = relative, M82 = absolute
    let currentType = 'DEFAULT';
    let currentFeedRate = 0; // mm/min as raw G-code value
    let currentPrintAccel = 0, currentTravelAccel = 0; // mm/s² from M204
    // Bambu Studio uses "; CHANGE_LAYER" as a marker, with layer number on a nearby line
    let pendingChangeLayer = false;
    let pendingZHeight = null;

    if (this.mode === 'cnc') {
      await this._parseCNC(this.lines, onProgress);
      return this.layers;
    }

    const CHUNK = 50000;
    const total = this.lines.length;

    for (let start = 0; start < total; start += CHUNK) {
      const end = Math.min(start + CHUNK, total);

    for (let i = start; i < end; i++) {
      const line = this.lines[i].trim();

      // Detect header end
      if (!foundFirstLayer && !this.headerEnd) {
        const lm = line.match(/^;LAYER:(\d+)/i) || line.match(/^; CHANGE_LAYER/) || line.match(/^; layer \d+, Z = /i) || line === ';LAYER_CHANGE';
        if (lm) { this.headerEnd = i; foundFirstLayer = true; }
        else if (line && !line.startsWith(';') && (line.startsWith('G') || line.startsWith('M') || line.startsWith('T'))) {
          if (!this.headerEnd) this.headerEnd = i;
        }
      }

      // Parse layer markers — standard format: ;LAYER:N
      const layerMatch = line.match(/^;LAYER:(\d+)/i);
      if (layerMatch) {
        foundFirstLayer = true;
        if (currentLayer) {
          currentLayer.endLine = i - 1;
          currentLayer.lineCount = currentLayer.endLine - currentLayer.startLine + 1;
        }
        currentLayer = {
          number: parseInt(layerMatch[1]),
          startLine: i, endLine: null, zHeight: null,
          sectionTypes: [], lineCount: 0
        };
        this.layers.push(currentLayer);
        this.layerMoves[currentLayer.number] = [];
        currentType = 'DEFAULT';
      }

      // Parse layer markers — Bambu Studio format: ; CHANGE_LAYER + ; Z_HEIGHT + ; layer num/total_layer_count
      if (line === '; CHANGE_LAYER') {
        pendingChangeLayer = true;
        pendingZHeight = null;
        // Mark the start line as this CHANGE_LAYER comment
        foundFirstLayer = true;
        if (currentLayer) {
          currentLayer.endLine = i - 1;
          currentLayer.lineCount = currentLayer.endLine - currentLayer.startLine + 1;
        }
        // Create a temporary layer — number will be updated when we find the layer num comment
        currentLayer = {
          number: this.layers.length, // temporary, updated below
          startLine: i, endLine: null, zHeight: null,
          sectionTypes: [], lineCount: 0,
          _pending: true
        };
        currentType = 'DEFAULT';
      }

      // Bambu: ; Z_HEIGHT: 0.2
      if (pendingChangeLayer) {
        const zHMatch = line.match(/^; Z_HEIGHT:\s*([\d.]+)/);
        if (zHMatch) {
          pendingZHeight = parseFloat(zHMatch[1]);
          if (currentLayer) currentLayer.zHeight = pendingZHeight;
        }

        // Bambu: ; layer num/total_layer_count: 1/525
        const bambuLayerMatch = line.match(/^; layer num\/total_layer_count:\s*(\d+)\/(\d+)/);
        if (bambuLayerMatch) {
          const layerNum = parseInt(bambuLayerMatch[1]) - 1; // Bambu uses 1-based, convert to 0-based
          if (currentLayer && currentLayer._pending) {
            currentLayer.number = layerNum;
            delete currentLayer._pending;
            this.layers.push(currentLayer);
            this.layerMoves[currentLayer.number] = [];
          }
          pendingChangeLayer = false;
        }
      }

      // Simplify3D: "; layer N, Z = X.XX"
      const s3dLayerMatch = line.match(/^; layer (\d+), Z = ([\d.]+)/i);
      if (s3dLayerMatch) {
        foundFirstLayer = true;
        if (currentLayer) {
          currentLayer.endLine = i - 1;
          currentLayer.lineCount = currentLayer.endLine - currentLayer.startLine + 1;
        }
        currentLayer = {
          number: parseInt(s3dLayerMatch[1]),
          startLine: i, endLine: null,
          zHeight: parseFloat(s3dLayerMatch[2]),
          sectionTypes: [], lineCount: 0
        };
        this.layers.push(currentLayer);
        this.layerMoves[currentLayer.number] = [];
        currentType = 'DEFAULT';
      }

      // PrusaSlicer alternative: ;LAYER_CHANGE + ;Z:X.XX
      if (line === ';LAYER_CHANGE') {
        foundFirstLayer = true;
        if (currentLayer) {
          currentLayer.endLine = i - 1;
          currentLayer.lineCount = currentLayer.endLine - currentLayer.startLine + 1;
        }
        currentLayer = {
          number: this.layers.length,
          startLine: i, endLine: null, zHeight: null,
          sectionTypes: [], lineCount: 0
        };
        this.layers.push(currentLayer);
        this.layerMoves[currentLayer.number] = [];
        currentType = 'DEFAULT';
      }
      if (currentLayer && !currentLayer.zHeight) {
        const zDirectMatch = line.match(/^;Z:([\d.]+)/);
        if (zDirectMatch) currentLayer.zHeight = parseFloat(zDirectMatch[1]);
      }

      // Extract Z-height (fallback from G0/G1 moves)
      if (currentLayer && !currentLayer.zHeight) {
        const zMatch = line.match(/G[01]\s.*Z([\d.]+)/i);
        if (zMatch) currentLayer.zHeight = parseFloat(zMatch[1]);
      }

      // Extract section types — standard: ;TYPE:X  or Bambu: ; FEATURE: X
      if (currentLayer) {
        const typeMatch = line.match(/^;TYPE:(.+)/i) || line.match(/^; FEATURE:\s*(.+)/i);
        if (typeMatch) {
          // Normalize slicer type names (PrusaSlicer, BambuStudio, SuperSlicer)
          const typeNormalize = {
            // PrusaSlicer / SuperSlicer
            'External perimeter': 'WALL-OUTER',
            'Perimeter': 'WALL-INNER',
            'Solid infill': 'SOLID',
            'Top solid infill': 'TOP',
            'Bottom solid infill': 'BOTTOM',
            'Bridge infill': 'BRIDGE',
            'Gap fill': 'GAP INFILL',
            'Overhang perimeter': 'OVERHANG',
            'Internal infill': 'FILL',
            'Sparse infill': 'FILL',
            'Skirt': 'SKIRT',
            'Skirt/Brim': 'SKIRT',
            'Support material': 'SUPPORT',
            'Support material interface': 'SUPPORT-INTERFACE',
            // BambuStudio
            'Inner wall': 'WALL-INNER',
            'Outer wall': 'WALL-OUTER',
            'Overhang wall': 'OVERHANG',
            'Internal solid infill': 'SOLID',
            'Bottom surface': 'BOTTOM',
            'Top surface': 'TOP',
            'Bridge': 'BRIDGE',
            'Sparse infill': 'FILL',
            'Brim': 'BRIM',
            'Support': 'SUPPORT',
            'Support interface': 'SUPPORT-INTERFACE',
          };
          const rawType = typeMatch[1].trim();
          currentType = typeNormalize[rawType] || rawType.toUpperCase();
          if (!currentLayer.sectionTypes.includes(currentType)) currentLayer.sectionTypes.push(currentType);
        }

        // Simplify3D: "; outer perimeter", "; inner perimeter", etc.
        if (!typeMatch) {
          const s3dType = line.match(/^; (outer perimeter|inner perimeter|solid layer|infill|support|raft|skirt|gap fill|bridge)/i);
          if (s3dType) {
            const typeMap = {
              'outer perimeter': 'WALL-OUTER',
              'inner perimeter': 'WALL-INNER',
              'solid layer': 'SOLID',
              'infill': 'FILL',
              'support': 'SUPPORT',
              'raft': 'SUPPORT',
              'skirt': 'SKIRT',
              'gap fill': 'GAP INFILL',
              'bridge': 'BRIDGE',
            };
            currentType = typeMap[s3dType[1].toLowerCase()] || s3dType[1].toUpperCase();
            if (!currentLayer.sectionTypes.includes(currentType)) currentLayer.sectionTypes.push(currentType);
          }
        }
      }

      // Track extrusion mode
      if (/^M83(\s|;|$)/.test(line)) relativeE = true;
      if (/^M82(\s|;|$)/.test(line)) relativeE = false;
      if (line.startsWith('G92') && line.includes('E')) { curE = 0; } // Reset E position

      // Track acceleration from M204
      if (/^M204\s/.test(line)) {
        const accelParams = {};
        for (const m of line.matchAll(/([PTSRE])([\d.]+)/gi)) accelParams[m[1].toUpperCase()] = parseFloat(m[2]);
        if (accelParams.S !== undefined) { currentPrintAccel = accelParams.S; currentTravelAccel = accelParams.S; } // legacy
        if (accelParams.P !== undefined) currentPrintAccel = accelParams.P;
        if (accelParams.T !== undefined) currentTravelAccel = accelParams.T;
      }

      // Parse G0/G1 linear moves for the viewer
      if (currentLayer && this.layerMoves[currentLayer.number] && /^G[01]\s/.test(line)) {
        try {
        const params = {};
        const matches = line.matchAll(/([XYZEF])([-\d.]+)/gi);
        for (const m of matches) params[m[1].toUpperCase()] = parseFloat(m[2]);

        const newX = params.X !== undefined ? params.X : curX;
        const newY = params.Y !== undefined ? params.Y : curY;
        const newZ = params.Z !== undefined ? params.Z : curZ;
        const isG0 = line.startsWith('G0');
        if (params.F !== undefined) currentFeedRate = params.F;
        const prevE = curE;
        let isExtrude = false;
        if (params.E !== undefined) {
          isExtrude = relativeE ? params.E > 0 : params.E > curE;
          curE = relativeE ? curE + params.E : params.E;
        }
        const eLength = Math.abs(curE - prevE);

        // Only record XY moves (skip pure Z moves)
        if (newX !== curX || newY !== curY) {
          this.layerMoves[currentLayer.number].push({
            x1: curX, y1: curY, x2: newX, y2: newY,
            type: currentType, extrude: isExtrude && !isG0, lineIndex: i,
            feedRate: currentFeedRate,
            accel: (isExtrude && !isG0) ? currentPrintAccel : currentTravelAccel,
            eLength: eLength
          });
          this.bounds.minX = Math.min(this.bounds.minX, curX, newX);
          this.bounds.maxX = Math.max(this.bounds.maxX, curX, newX);
          this.bounds.minY = Math.min(this.bounds.minY, curY, newY);
          this.bounds.maxY = Math.max(this.bounds.maxY, curY, newY);
        }

        curX = newX; curY = newY; curZ = newZ;
        } catch (err) {
          this.skippedLines++;
        }
      }

      // Parse G2/G3 arc moves (Bambu Studio uses arc fitting)
      if (currentLayer && this.layerMoves[currentLayer.number] && /^G[23]\s/.test(line)) {
        try {
        const params = {};
        const matches = line.matchAll(/([XYZEFIJ])([-\d.]+)/gi);
        for (const m of matches) params[m[1].toUpperCase()] = parseFloat(m[2]);

        const newX = params.X !== undefined ? params.X : curX;
        const newY = params.Y !== undefined ? params.Y : curY;
        if (params.F !== undefined) currentFeedRate = params.F;
        const prevE = curE;
        let isExtrude = false;
        if (params.E !== undefined) {
          isExtrude = relativeE ? params.E > 0 : params.E > curE;
          curE = relativeE ? curE + params.E : params.E;
        }
        const totalELength = Math.abs(curE - prevE);
        const isG2 = line.startsWith('G2'); // clockwise

        // Approximate arc with line segments
        const cx = curX + (params.I || 0);
        const cy = curY + (params.J || 0);
        const r = Math.hypot(params.I || 0, params.J || 0);
        if (r > 0.01) {
          let startAngle = Math.atan2(curY - cy, curX - cx);
          let endAngle = Math.atan2(newY - cy, newX - cx);
          // Adjust sweep direction
          if (isG2) { // CW
            if (endAngle >= startAngle) endAngle -= 2 * Math.PI;
          } else { // CCW
            if (endAngle <= startAngle) endAngle += 2 * Math.PI;
          }
          const segments = Math.max(4, Math.ceil(Math.abs(endAngle - startAngle) / (Math.PI / 12)));
          let prevAX = curX, prevAY = curY;
          for (let s = 1; s <= segments; s++) {
            const t = s / segments;
            const angle = startAngle + (endAngle - startAngle) * t;
            const ax = s === segments ? newX : cx + r * Math.cos(angle);
            const ay = s === segments ? newY : cy + r * Math.sin(angle);
            this.layerMoves[currentLayer.number].push({
              x1: prevAX, y1: prevAY, x2: ax, y2: ay,
              type: currentType, extrude: isExtrude, lineIndex: i,
              feedRate: currentFeedRate,
              accel: isExtrude ? currentPrintAccel : currentTravelAccel,
              eLength: totalELength / segments
            });
            this.bounds.minX = Math.min(this.bounds.minX, ax);
            this.bounds.maxX = Math.max(this.bounds.maxX, ax);
            this.bounds.minY = Math.min(this.bounds.minY, ay);
            this.bounds.maxY = Math.max(this.bounds.maxY, ay);
            prevAX = ax; prevAY = ay;
          }
        }

        curX = newX; curY = newY;
        } catch (err) {
          this.skippedLines++;
        }
      }
    }

      if (onProgress) onProgress(Math.min(end / total, 1));
      if (end < total) await new Promise(r => setTimeout(r, 0));
    }

    // Finalize any pending Bambu layer that never got its layer num line
    if (currentLayer && currentLayer._pending) {
      delete currentLayer._pending;
      this.layers.push(currentLayer);
      this.layerMoves[currentLayer.number] = [];
    }

    // Close last layer
    if (currentLayer) {
      currentLayer.endLine = this.lines.length - 1;
      currentLayer.lineCount = currentLayer.endLine - currentLayer.startLine + 1;
    }

    // Sanitize bounds
    if (!isFinite(this.bounds.minX)) this.bounds = { minX: 0, maxX: 256, minY: 0, maxY: 256 };

    return this.layers;
  }

  getLayerByNumber(num) {
    return this.layers.find(l => l.number === num);
  }
}
